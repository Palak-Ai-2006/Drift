#!/usr/bin/env python
"""Round 4 write-up: generates the results section from
artifacts/metrics_synth.json + round4_dev_results.json + round4_test_misses.csv
and inserts it (between markers) into MODEL_CARD.md and SYNTHETIC_PLAN.md.
No number in these sections is typed by hand (CLAUDE.md Section 12).
"""

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from drift import config  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "artifacts"
START, END = "<!-- ROUND4_RESULTS:START -->", "<!-- ROUND4_RESULTS:END -->"


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


def ci(v, p=True):
    if not v or v[0] is None:
        return ""
    return f" [{100 * v[0]:.1f}–{100 * v[1]:.1f}]" if p else f" [{v[0]:.2f}–{v[1]:.2f}]"


def mins(x):
    return "n/a" if x is None else f"{x:.1f}"


def tier_table(per_tier):
    lines = [
        "| Tier | Collapses | Drift model sensitivity [95% CI] | Model FA/hr [95% CI] | Model lead, median (IQR) min "
        "| B2 (MAP cutoff) sens / FA/hr / lead | Standard monitor FA/hr / lead | Model − standard monitor lead (median, min) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for tier, r in per_tier.items():
        m, b, s = r["model@1.0FA"], r["b2@1.0FA"], r["standard_monitor"]
        lt = m["lead_time"]
        name = "All tiers" if tier == "ALL" else f"{tier} {config.SYNTH_TIER_NAMES[tier]}"
        lines.append(
            f"| {name} | {m['n_collapses']} | {pct(m['sensitivity'])}{ci(m['bootstrap']['sensitivity_ci95'])} "
            f"| {m['fa_per_hour']:.2f}{ci(m['bootstrap']['fa_per_hour_ci95'], p=False)} "
            f"| {mins(lt['median_s'])} ({mins(lt['iqr_low_s'])}–{mins(lt['iqr_high_s'])}) "
            f"| {pct(b['sensitivity'])} / {b['fa_per_hour']:.2f} / {mins(b['lead_time']['median_s'])} "
            f"| {s['fa_per_hour']:.2f} / {mins(s['lead_time']['median_s'])} "
            f"| {mins(r['model_minus_standard_monitor_lead_min_median'])} |"
        )
    return "\n".join(lines)


def build_section():
    m = json.loads((ART / "metrics_synth.json").read_text())
    dev = json.loads((ART / "round4_dev_results.json").read_text())
    misses = pd.read_csv(ART / "round4_test_misses.csv")
    test, shifted = m["sets"]["test"], m["sets"]["test_shifted"]
    tgt = m["preregistered_target_check"]
    b2_cut = -dev["thresholds"]["b2"]["1.0"]["threshold"]
    all_t = test["per_tier"]["ALL"]
    tm = misses[misses["set"] == "test"]
    top_src = tm["source_caseid"].value_counts()
    nc, nbh = test["bleed_no_collapse_descriptive"], test["non_bleed_hypotension_descriptive"]

    target_lines = "\n".join(
        f"- **{t}:** sensitivity {pct(v['sensitivity'])}{ci(test['per_tier'][t]['model@1.0FA']['bootstrap']['sensitivity_ci95'])}, "
        f"{v['fa_per_hour']:.2f} false alarms/hr → target {'**met**' if v['target_met'] else '**not met**'} (point estimate)"
        for t, v in tgt.items()
    )
    other_fa = (
        f"At 0.5 FA/hr (val threshold) the model's test sensitivity over all tiers is {pct(all_t['model@0.5FA']['sensitivity'])} "
        f"vs B2 {pct(all_t['b2@0.5FA']['sensitivity'])}. At 2 FA/hr it's {pct(all_t['model@2.0FA']['sensitivity'])} "
        f"vs B2 {pct(all_t['b2@2.0FA']['sensitivity'])}."
    )
    nc_bins = ", ".join(f"{k} {v:.2f}" for k, v in nc["median_risk_by_blood_loss"].items() if v is not None)
    briers = ", ".join(f"{t} {r['secondary_auroc_auprc_brier']['brier']:.3f}" for t, r in test["per_tier"].items())

    return f"""{START}
## Round 4: semi-synthetic results (SIMULATION, generated by `scripts/10_round4_report.py`)

**Every number in this section is from a simulation.** Real, stable VitalDB baselines have simulated bleeds injected on top. The simulation assumes that compensation (heart rate up, pulse pressure down) comes before collapse, so these results show the method works *when that is true*. They cannot show that it *is* true in real patients. Design: [SYNTHETIC_PLAN.md](SYNTHETIC_PLAN.md) §3–5a. Generator frozen by fingerprint (`artifacts/round4_generator_freeze.json`) before training. The test set was evaluated once.

**Model:** {dev['chosen_model']} regression on the Phase 3 causal features, trained on synth-train across all tiers and chosen on synth-val ({dev['selection_reason']}). It was calibrated (isotonic) on synth-val, and one 1 FA/hr threshold from synth-val is used for every tier. **B2** at the same target alarms when MAP < {b2_cut:.1f} mmHg. **Standard monitor** = MAP < 65 OR HR > 120 OR SBP < 90 (typical settings, not a verified default). **B1** = MAP < 65 itself (zero lead).

**Pre-registered target (≥ 95% sensitivity at ≤ 1 FA/hr on T1 and T2):**
{target_lines}

### Synth-test, per tier, at the 1 FA/hr operating point
{tier_table(test['per_tier'])}

Lead time is capped at 15 min by the horizon. False alarm means no MAP < 65 event within 15 min; this is conservative, because a correct alert 20 min before collapse counts as false. Under the secondary "bleed-aware" count (alerts after bleed onset are not false), all-tier FA/hr is: model {all_t['model@1.0FA']['fa_per_hour_bleed_aware']:.2f}, B2 {all_t['b2@1.0FA']['fa_per_hour_bleed_aware']:.2f}, standard monitor {all_t['standard_monitor']['fa_per_hour_bleed_aware']:.2f}.

{other_fa}

### Shifted test (slower bleeds, lower HR gain, later onset than training)
{tier_table(shifted['per_tier'])}

### Misses, other classes, calibration
- **Misses (synth-test, model at 1 FA/hr): {len(tm)}.** By cause: {", ".join(f"{k} {v}" for k, v in m['misses_by_cause'].items())}. B2 caught {int(tm['b2_detected'].sum())} of them. {int(top_src.iloc[0]) if len(top_src) else 0} come from a single real baseline patient (VitalDB case {int(top_src.index[0]) if len(top_src) else 'n/a'}). Full list: `artifacts/round4_test_misses.csv`.
- **`bleed_no_collapse` (descriptive, not scored), {nc['n_streams']} streams:** median calibrated risk by blood lost: {nc_bins}. Alerted after bleed onset: {pct(nc['fraction_alerted_after_onset_at_1FA'])}; before onset (a false alert): {pct(nc['fraction_alerted_before_onset_at_1FA'])}.
- **Non-bleed hypotension (T4 no-bleed streams whose MAP fell below 65):** {nbh['n_detected_model@1FA']} of {nbh['n_events']} warned early. This is expected: by design there is no heart-rate or pulse-pressure precursor.
- **Calibration (Brier, synth-test):** {briers}. Reliability plot: `artifacts/round4_reliability_plot.png`.

### What this does and doesn't show
- **Does:** when bleeding produces textbook compensation, a simple calibrated model on heart-rate, pulse-pressure and MAP trends warns about twice as early as a MAP cutoff ({mins(all_t['model@1.0FA']['lead_time']['median_s'])} vs {mins(all_t['b2@1.0FA']['lead_time']['median_s'])} min median) with fewer false alarms ({all_t['model@1.0FA']['fa_per_hour']:.2f} vs {all_t['b2@1.0FA']['fa_per_hour']:.2f}/hr). It warns a median {mins(all_t['model_minus_standard_monitor_lead_min_median'])} min earlier than a standard HR/SBP/MAP monitor, which raises fewer false alarms ({all_t['standard_monitor']['fa_per_hour']:.2f}/hr).
- **Doesn't:** it doesn't catch *more* collapses than a well-tuned MAP cutoff (both are near the ceiling), and it says nothing about real patients. On real surgical data (Rounds 1–3) MAP alone matched these features, consistent with the published debate over whether the Hypotension Prediction Index adds anything beyond MAP. The simulation can't settle which world real trauma patients live in; that needs data with real bleed labels.
{END}"""


def insert(path: Path, section: str, anchor: str):
    text = path.read_text()
    if START in text:
        pre, rest = text.split(START, 1)
        post = rest.split(END, 1)[1]
        text = pre + section + post
    else:
        text = text.replace(anchor, section + "\n\n" + anchor, 1)
    path.write_text(text)
    print(f"Updated {path.name}")


if __name__ == "__main__":
    sec = build_section()
    insert(ROOT / "MODEL_CARD.md", sec, "## What this is not")
    insert(ROOT / "SYNTHETIC_PLAN.md", sec, "## Sources")
